-- Adds normalized parlay tickets without changing the existing single-bet fields
-- on fight_research. Run once in the Supabase SQL editor before using v5.

create table if not exists public.bet_tickets (
  ticket_id bigint generated by default as identity primary key,
  owner_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  ticket_type text not null default 'parlay'
    check (ticket_type in ('parlay')),
  ticket_label text not null default '',
  bet_sportsbook text not null default '',
  ticket_price integer not null
    check (ticket_price <= -100 or ticket_price >= 100),
  stake_units numeric(7, 2) not null
    check (stake_units > 0),
  settlement_status text not null default 'pending'
    check (settlement_status in ('pending', 'win', 'loss', 'push', 'void')),
  settled_at timestamptz null,
  placed_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bet_legs (
  leg_id bigint generated by default as identity primary key,
  ticket_id bigint not null references public.bet_tickets(ticket_id) on delete cascade,
  fight_id bigint not null references public.fights(fight_id) on delete cascade,
  bet_side text not null check (bet_side in ('fighter_a', 'fighter_b')),
  leg_price integer not null
    check (leg_price <= -100 or leg_price >= 100),
  leg_order smallint not null check (leg_order > 0),
  created_at timestamptz not null default now(),
  unique (ticket_id, fight_id),
  unique (ticket_id, leg_order)
);

create index if not exists bet_tickets_owner_id_idx
  on public.bet_tickets(owner_id);
create index if not exists bet_legs_ticket_id_idx
  on public.bet_legs(ticket_id);
create index if not exists bet_legs_fight_id_idx
  on public.bet_legs(fight_id);

alter table public.bet_tickets enable row level security;
alter table public.bet_legs enable row level security;

revoke all privileges on table public.bet_tickets from anon;
revoke all privileges on table public.bet_legs from anon;
grant select, insert, update, delete on public.bet_tickets to authenticated;
grant select, insert, update, delete on public.bet_legs to authenticated;
grant usage, select on all sequences in schema public to authenticated;

drop policy if exists bet_tickets_owner_select on public.bet_tickets;
drop policy if exists bet_tickets_owner_insert on public.bet_tickets;
drop policy if exists bet_tickets_owner_update on public.bet_tickets;
drop policy if exists bet_tickets_owner_delete on public.bet_tickets;

create policy bet_tickets_owner_select
  on public.bet_tickets for select to authenticated
  using (owner_id = auth.uid());
create policy bet_tickets_owner_insert
  on public.bet_tickets for insert to authenticated
  with check (owner_id = auth.uid());
create policy bet_tickets_owner_update
  on public.bet_tickets for update to authenticated
  using (owner_id = auth.uid())
  with check (owner_id = auth.uid());
create policy bet_tickets_owner_delete
  on public.bet_tickets for delete to authenticated
  using (owner_id = auth.uid());

drop policy if exists bet_legs_owner_select on public.bet_legs;
drop policy if exists bet_legs_owner_insert on public.bet_legs;
drop policy if exists bet_legs_owner_update on public.bet_legs;
drop policy if exists bet_legs_owner_delete on public.bet_legs;

create policy bet_legs_owner_select
  on public.bet_legs for select to authenticated
  using (exists (
    select 1 from public.bet_tickets ticket
    where ticket.ticket_id = bet_legs.ticket_id
      and ticket.owner_id = auth.uid()
  ));
create policy bet_legs_owner_insert
  on public.bet_legs for insert to authenticated
  with check (exists (
    select 1 from public.bet_tickets ticket
    where ticket.ticket_id = bet_legs.ticket_id
      and ticket.owner_id = auth.uid()
  ));
create policy bet_legs_owner_update
  on public.bet_legs for update to authenticated
  using (exists (
    select 1 from public.bet_tickets ticket
    where ticket.ticket_id = bet_legs.ticket_id
      and ticket.owner_id = auth.uid()
  ))
  with check (exists (
    select 1 from public.bet_tickets ticket
    where ticket.ticket_id = bet_legs.ticket_id
      and ticket.owner_id = auth.uid()
  ));
create policy bet_legs_owner_delete
  on public.bet_legs for delete to authenticated
  using (exists (
    select 1 from public.bet_tickets ticket
    where ticket.ticket_id = bet_legs.ticket_id
      and ticket.owner_id = auth.uid()
  ));

comment on table public.bet_tickets is
  'Personal multi-leg moneyline parlay tickets; existing singles remain on fight_research.';
comment on column public.bet_tickets.ticket_price is
  'Combined American odds actually accepted for the complete parlay ticket.';
comment on column public.bet_legs.leg_price is
  'American moneyline price for this leg when the parlay was placed, used for tracked-close diagnostics.';

notify pgrst, 'reload schema';
