-- Automatically audit fighters on upcoming cards and retain targeted fallback
-- history without creating regional event rows in the main event selector.

insert into public.data_sources (name)
select 'Sherdog Fighter History'
where not exists (
  select 1 from public.data_sources where name = 'Sherdog Fighter History'
);

create table if not exists public.fighter_history_entries (
  fighter_history_entry_id bigint generated by default as identity primary key,
  fighter_id bigint not null references public.fighters(fighter_id) on delete cascade,
  source_id bigint references public.data_sources(source_id),
  external_bout_id text not null,
  source_url text,
  event_name text,
  event_date date,
  promotion_name text,
  opponent_name text not null,
  opponent_record text,
  outcome text not null default '—'
    check (outcome in ('W', 'L', 'D', 'NC', 'CANCELLED', '—')),
  method text,
  finish_round integer,
  finish_time_seconds integer,
  fight_status text not null default 'completed',
  is_title_fight boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (fighter_id, source_id, external_bout_id)
);

create index if not exists fighter_history_entries_fighter_date_idx
  on public.fighter_history_entries (fighter_id, event_date desc);

create table if not exists public.fighter_history_coverage (
  fighter_id bigint primary key references public.fighters(fighter_id) on delete cascade,
  history_fighter_id bigint references public.fighters(fighter_id) on delete set null,
  next_event_id bigint references public.events(event_id) on delete set null,
  next_event_name text,
  next_event_date date,
  promotion_name text,
  coverage_status text not null default 'pending'
    check (coverage_status in (
      'pending',
      'complete',
      'linked_history',
      'fallback_history',
      'confirmed_debut',
      'regional_history_unavailable',
      'history_unavailable',
      'needs_review'
    )),
  record_summary text,
  known_bout_count integer not null default 0,
  source_used text,
  coverage_note text,
  attempts jsonb not null default '[]'::jsonb,
  last_checked_at timestamptz,
  next_check_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists fighter_history_coverage_upcoming_idx
  on public.fighter_history_coverage (next_event_date, coverage_status);

create table if not exists public.history_maintenance_runs (
  history_maintenance_run_id bigint generated by default as identity primary key,
  started_at timestamptz not null,
  finished_at timestamptz,
  status text not null default 'running'
    check (status in ('running', 'success', 'partial', 'failed')),
  fighters_checked integer not null default 0,
  histories_found integer not null default 0,
  confirmed_debuts integer not null default 0,
  unavailable_histories integer not null default 0,
  needs_review integer not null default 0,
  summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.fighter_history_entries enable row level security;
alter table public.fighter_history_coverage enable row level security;
alter table public.history_maintenance_runs enable row level security;

revoke all privileges on table public.fighter_history_entries from anon;
revoke all privileges on table public.fighter_history_coverage from anon;
revoke all privileges on table public.history_maintenance_runs from anon;

grant select on table public.fighter_history_entries to authenticated;
grant select on table public.fighter_history_coverage to authenticated;
grant select on table public.history_maintenance_runs to authenticated;

drop policy if exists dashboard_authenticated_read on public.fighter_history_entries;
create policy dashboard_authenticated_read
  on public.fighter_history_entries for select to authenticated using (true);

drop policy if exists dashboard_authenticated_read on public.fighter_history_coverage;
create policy dashboard_authenticated_read
  on public.fighter_history_coverage for select to authenticated using (true);

drop policy if exists dashboard_authenticated_read on public.history_maintenance_runs;
create policy dashboard_authenticated_read
  on public.history_maintenance_runs for select to authenticated using (true);

notify pgrst, 'reload schema';
