-- Stores a small audit record for each scheduled data refresh.
-- Public event/fight data still lives in its existing normalized tables.
create table if not exists public.data_sync_runs (
  data_sync_run_id bigint generated by default as identity primary key,
  started_at timestamptz not null,
  finished_at timestamptz null,
  status text not null
    check (status in ('running', 'success', 'partial', 'failed')),
  events_processed integer not null default 0,
  fights_processed integer not null default 0,
  results_processed integer not null default 0,
  odds_status text null,
  summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists data_sync_runs_started_at_idx
  on public.data_sync_runs (started_at desc);

grant select on public.data_sync_runs to anon, authenticated;
grant insert on public.data_sync_runs to service_role;

alter table public.data_sync_runs disable row level security;

comment on table public.data_sync_runs is
  'Audit history for local scheduled UFC/DWCS, result, stat, and odds refreshes.';

notify pgrst, 'reload schema';
