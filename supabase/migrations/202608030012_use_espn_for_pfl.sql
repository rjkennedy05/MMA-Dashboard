-- Register the no-key ESPN MMA source used for current PFL cards/results.
insert into public.data_sources (name)
select 'ESPN MMA'
where not exists (
  select 1
  from public.data_sources
  where lower(name) in ('espn mma', 'espn')
);

-- Repair sync-health writes for the current local, single-user deployment.
-- Authentication/RLS hardening remains deferred until public deployment.
create table if not exists public.data_sync_runs (
  data_sync_run_id bigint generated by default as identity primary key,
  started_at timestamptz not null,
  finished_at timestamptz null,
  status text not null
    check (status in ('running', 'success', 'partial', 'failed')),
  events_processed integer not null default 0,
  fights_processed integer not null default 0,
  results_processed integer not null default 0,
  odds_status text null,
  summary jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

grant select, insert on public.data_sync_runs
  to anon, authenticated, service_role;

grant usage, select
  on sequence public.data_sync_runs_data_sync_run_id_seq
  to anon, authenticated, service_role;

alter table public.data_sync_runs disable row level security;

