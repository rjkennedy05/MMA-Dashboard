test('an unknown cascading dependency cannot silently lose data', async () => {
  await db.exec('create table extra_fight_data(bout_id bigint references fights on delete cascade, notes text); insert into extra_fight_data values(9541,\'Keep this attachment\')');
  await expectUnchanged(/additional linked data/);
  assert.equal((await db.query('select notes from extra_fight_data')).rows[0].notes, 'Keep this attachment');
});

