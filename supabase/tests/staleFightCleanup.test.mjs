async function snapshot() {
  const result = {};
  for (const table of tables) {
    result[table] = (await db.query(`select to_jsonb(r) row from public.${table} r order by to_jsonb(r)::text`)).rows;
  }
  return result;
}

async function expectUnchanged(message) {
  const before = await snapshot();
  await assert.rejects(db.exec(cleanup), message);
  await db.exec('rollback');
  assert.deepEqual(await snapshot(), before);
  assert.equal((await db.query("select to_regclass('mma_recovery.fight_cleanups') backup")).rows[0].backup, null);
}

test('cleanup removes only #9541 and saves all removed source data privately', async () => {
  const before = await snapshot();
  await db.exec(cleanup);
  assert.equal((await db.query('select count(*)::int n from fights')).rows[0].n, 11);
  assert.equal((await db.query('select count(*)::int n from fights where fight_id=9540')).rows[0].n, 1);
  assert.deepEqual((await snapshot()).fight_research, before.fight_research);
  assert.deepEqual((await snapshot()).bet_legs, before.bet_legs);
  assert.deepEqual((await snapshot()).fighters, before.fighters);
  assert.equal((await db.query("select count(*)::int n from external_ids where entity_type='fighter' and internal_id=9541")).rows[0].n, 1);
  const backup = (await db.query('select payload from mma_recovery.fight_cleanups')).rows[0].payload;
  for (const table of ['fights','odds','mma_odds_observations','fight_stats','fight_round_stats','external_ids','mma_external_aliases']) {
    assert.equal(backup[table].length, 1, table);
  }
  assert.equal((await db.query("select has_schema_privilege('anon','mma_recovery','usage') access")).rows[0].access, false);
  assert.equal((await db.query("select has_table_privilege('authenticated','mma_recovery.fight_cleanups','select') access")).rows[0].access, false);
});

test('repeated cleanup keeps the original recovery copy', async () => {
  await db.exec(cleanup);
  const before = (await db.query('select * from mma_recovery.fight_cleanups')).rows;
  await db.exec(cleanup);
  assert.deepEqual((await db.query('select * from mma_recovery.fight_cleanups')).rows, before);
});

test('recovery restores every original row and is repeatable', async () => {
  const before = await snapshot();
  await db.exec(cleanup);
  await db.exec(restore);
  assert.deepEqual(await snapshot(), before);
  await db.exec(restore);
  assert.deepEqual(await snapshot(), before);
});

