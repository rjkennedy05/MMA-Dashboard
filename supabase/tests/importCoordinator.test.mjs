async function save(entity, payload, external="source1", existing=null, source=42, catalog=false, owner=null, fence=null) {
  return (await db.query(`select public.mma_upsert_import_entity($1,$2::jsonb,$3,$4,$5,null,$6,$7,$8) as result`,
    [entity,JSON.stringify(payload),source,external,existing,owner,fence,catalog])).rows[0].result;
}
